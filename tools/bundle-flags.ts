import { readFile, writeFile, mkdir, copyFile, readdir, rm } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

/**
 * Flags ship as one module per country so an app bundles only the flags it imports:
 * `import tw from '@everylocale/react/flags/tw'`. The workspace serves the same SVG files.
 */
const manifest = fileURLToPath(import.meta.resolve('flag-icons/package.json'));
const source = dirname(manifest);
const { version } = JSON.parse(await readFile(manifest, 'utf8')) as { version: string };
const directory = join(source, 'flags', '4x3');
const countries = (await readdir(directory))
  .filter((name) => /^[a-z]{2}\.svg$/.test(name))
  .map((name) => name.slice(0, 2));

const reactFlags = 'packages/react/flags';
const publicFlags = 'packages/server/public/flags';
await rm(reactFlags, { recursive: true, force: true });
await mkdir(reactFlags, { recursive: true });
await mkdir(publicFlags, { recursive: true });
const header = `// flag-icons ${version}, MIT, copyright Panayiotis Lipiridis. Generated by tools/bundle-flags.ts.\n`;
for (const country of countries) {
  const svg = await readFile(join(directory, `${country}.svg`), 'utf8');
  await writeFile(
    join(reactFlags, `${country}.js`),
    `${header}export default ${JSON.stringify(svg)};\n`,
  );
  await writeFile(
    join(reactFlags, `${country}.d.ts`),
    `/** SVG markup of the ${country.toUpperCase()} flag. */\ndeclare const flag: string;\nexport default flag;\n`,
  );
  await writeFile(join(publicFlags, `${country}.svg`), svg);
}
await copyFile(join(source, 'LICENSE'), join(reactFlags, 'LICENSE'));
await copyFile(join(source, 'LICENSE'), join(publicFlags, 'LICENSE'));
console.log(`Bundled ${String(countries.length)} flags from flag-icons ${version}.`);
