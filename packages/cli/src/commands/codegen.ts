import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { parse, TYPE, type MessageFormatElement } from '@formatjs/icu-messageformat-parser';
import type { SourceUnit } from '@everylocale/core';
import type { Workspace } from '../project.js';
import { atomicWrite } from '../release.js';

type Kind = 'text' | 'number' | 'date' | 'tag' | { select: Set<string> };
const STRICTNESS: Record<string, number> = { tag: 4, number: 3, date: 2, select: 1, text: 0 };
const strictness = (kind: Kind) => STRICTNESS[typeof kind === 'string' ? kind : 'select'] ?? 0;

/** Collects each argument's type; a stricter use wins, so `{n}` plus `{n, plural}` is a number. */
function argumentsOf(nodes: MessageFormatElement[], into = new Map<string, Kind>()) {
  const use = (name: string, kind: Kind) => {
    const previous = into.get(name);
    if (previous && typeof previous !== 'string' && typeof kind !== 'string')
      for (const key of kind.select) previous.select.add(key);
    else if (!previous || strictness(kind) > strictness(previous)) into.set(name, kind);
  };
  for (const node of nodes) {
    switch (node.type) {
      case TYPE.argument:
        use(node.value, 'text');
        break;
      case TYPE.number:
        use(node.value, 'number');
        break;
      case TYPE.date:
      case TYPE.time:
        use(node.value, 'date');
        break;
      case TYPE.tag:
        use(node.value, 'tag');
        argumentsOf(node.children, into);
        break;
      case TYPE.plural:
        use(node.value, 'number');
        for (const option of Object.values(node.options)) argumentsOf(option.value, into);
        break;
      case TYPE.select:
        use(node.value, {
          select: new Set(Object.keys(node.options).filter((key) => key !== 'other')),
        });
        for (const option of Object.values(node.options)) argumentsOf(option.value, into);
        break;
      default:
        break;
    }
  }
  return into;
}

const typeOf = (kind: Kind) =>
  kind === 'text'
    ? 'string | number'
    : kind === 'number'
      ? 'number'
      : kind === 'date'
        ? 'Date | number'
        : kind === 'tag'
          ? 'Tag'
          : [...kind.select]
              .map((key) => JSON.stringify(key))
              .concat('(string & {})')
              .join(' | ');

function declarations(units: readonly SourceUnit[]): string {
  const entries = [...units]
    .sort((a, b) => a.id.localeCompare(b.id))
    .map((unit) => {
      const args = unit.kind === 'icu' ? argumentsOf(parse(unit.source)) : new Map<string, Kind>();
      const values = args.size
        ? `{ ${[...args]
            .sort(([a], [b]) => a.localeCompare(b))
            .map(([name, kind]) => `${JSON.stringify(name)}: ${typeOf(kind)}`)
            .join('; ')} }`
        : 'undefined';
      return `      ${JSON.stringify(unit.id)}: ${values};`;
    });
  return [
    '// Generated by everylocale codegen from the source message files. Do not edit.',
    "import type { Tag } from '@everylocale/runtime';",
    '',
    "declare module '@everylocale/runtime' {",
    '  interface Register {',
    '    messages: {',
    ...entries,
    '    };',
    '  }',
    '}',
    '',
  ].join('\n');
}

/** Writes the declarations, or with `check` fails when the committed file is out of date. */
export async function codegen(workspace: Workspace, check: boolean): Promise<string> {
  const units: SourceUnit[] = [];
  for (const source of workspace.sources)
    if (source.kind === 'messages')
      units.push(...workspace.extract(source, await workspace.read(source)).units);
  const text = declarations(units);
  const path = join(workspace.root, workspace.config.codegen.output);
  if (check) {
    let current = '';
    try {
      current = await readFile(path, 'utf8');
    } catch {
      // A missing file is reported below as out of date.
    }
    if (current !== text)
      throw new Error(`${workspace.config.codegen.output} is out of date; run everylocale codegen`);
    return path;
  }
  await atomicWrite(path, text);
  return path;
}
